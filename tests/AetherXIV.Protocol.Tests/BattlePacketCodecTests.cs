    [Fact]
    public void CommandResultX00DecodesTraceConfirmedNoActionLayout()
    {
        byte[] payload =
        [
            0x41, 0x29, 0x9B, 0x02, 0x62, 0x00, 0x00, 0x7C,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x10, 0x08
        ];

        CommandResultX00PacketCodec codec = new();
        SubPacket subPacket = SubPacket.Create(PacketOpcode.CommandResultX00, 0x029B2941, payload);

        CommandResultX00Packet decoded = codec.Decode(subPacket);
        SubPacket encoded = codec.Encode(decoded.ActorId, decoded);

        Assert.Equal(0x029B2941u, decoded.ActorId);
        Assert.Equal(0x7C000062u, decoded.AnimationId);
        Assert.Equal(0, decoded.CommandId);
        Assert.Equal(0x0810, decoded.LayoutFlags);
        Assert.Equal(payload, decoded.RawPayload.ToArray());
        Assert.Equal(payload, encoded.Payload.ToArray());
    }

